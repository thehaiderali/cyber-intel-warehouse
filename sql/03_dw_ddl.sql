/*
   03_dw_ddl.sql
   Warehouse layer (schema project_dw) - physical implementation of the
   Phase 1 dimensional model.

   9 dimensions : dim_date, dim_cve, dim_product, dim_software, dim_asset,
                  dim_cvss, dim_cwe, dim_kev_status, dim_risk_band
   3 bridges    : bridge_cve_product, bridge_cve_cwe, bridge_product_software_map
   3 facts      : fact_vulnerability_intelligence_snapshot  (CVE x snapshot date)
                  fact_asset_software_inventory_snapshot    (asset x software x snapshot date)
                  fact_asset_vulnerability_exposure         (CVE x asset x software x assessment date)

   Key conventions
     * Every dimension has a surrogate key (BIGINT IDENTITY) plus its natural
       business key kept for traceability (cve_id, asset_id, cwe_code, ...).
     * dim_date uses a smart key in YYYYMMDD format.
     * dim_asset keys start at 1001 (asset_id 'AST-APACHE-01' -> asset_key 1001).
     * Key -1 is reserved in every dimension for the "Unknown / Not applicable"
       member, so fact rows never need a NULL foreign key.
     * dim_cve and dim_asset are SCD Type 2 (effective_start_date,
       effective_end_date, is_current). Only one current row per natural key.
     * Fact flags are SMALLINT 0/1 so they can be summed (e.g. SUM(kev_listed_flag)).

   Run: psql -U postgres -d intel_dw -f sql/03_dw_ddl.sql
   Re-runnable: drops and recreates the warehouse objects (data is lost).
*/

SET client_min_messages = warning;
SET search_path = project_dw;

DROP TABLE IF EXISTS fact_asset_vulnerability_exposure        CASCADE;
DROP TABLE IF EXISTS fact_asset_software_inventory_snapshot   CASCADE;
DROP TABLE IF EXISTS fact_vulnerability_intelligence_snapshot CASCADE;
DROP TABLE IF EXISTS bridge_product_software_map CASCADE;
DROP TABLE IF EXISTS bridge_cve_cwe              CASCADE;
DROP TABLE IF EXISTS bridge_cve_product          CASCADE;
DROP TABLE IF EXISTS dim_risk_band   CASCADE;
DROP TABLE IF EXISTS dim_kev_status  CASCADE;
DROP TABLE IF EXISTS dim_cwe         CASCADE;
DROP TABLE IF EXISTS dim_cvss        CASCADE;
DROP TABLE IF EXISTS dim_asset       CASCADE;
DROP TABLE IF EXISTS dim_software    CASCADE;
DROP TABLE IF EXISTS dim_product     CASCADE;
DROP TABLE IF EXISTS dim_cve         CASCADE;
DROP TABLE IF EXISTS dim_date        CASCADE;


-- 1. Dimensions

CREATE TABLE dim_date (
    date_key        INTEGER      PRIMARY KEY,                -- YYYYMMDD, -1 = unknown date
    full_date       DATE         UNIQUE,                     -- NULL only for the unknown member
    day_number      SMALLINT,                                -- day of month
    day_name        VARCHAR(10),
    week_number     SMALLINT,                                -- ISO week
    month_number    SMALLINT,
    month_name      VARCHAR(10),
    quarter_number  SMALLINT,
    year_number     SMALLINT,
    is_weekend      BOOLEAN
);
COMMENT ON TABLE dim_date IS 'Calendar dimension. Role-playing: published, last modified, KEV added, KEV due, snapshot and assessment dates.';

CREATE TABLE dim_cve (
    cve_key                 BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cve_id                  VARCHAR(30)  NOT NULL,           -- natural key, e.g. CVE-2021-41773
    source_identifier       VARCHAR(255),
    vulnerability_status    VARCHAR(50),
    description_en          TEXT,
    primary_cwe_code        VARCHAR(30),
    published_date_key      INTEGER      NOT NULL REFERENCES dim_date (date_key),
    last_modified_date_key  INTEGER      NOT NULL REFERENCES dim_date (date_key),
    last_modified_at        TIMESTAMP,                       -- exact NVD lastModified, drives change detection
    record_source           VARCHAR(20)  NOT NULL DEFAULT 'NVD',
    row_hash                CHAR(32)     NOT NULL,           -- md5 of the tracked attributes
    effective_start_date    DATE         NOT NULL,
    effective_end_date      DATE         NOT NULL DEFAULT DATE '9999-12-31',
    is_current              BOOLEAN      NOT NULL DEFAULT TRUE,
    CHECK (effective_end_date >= effective_start_date)
);
CREATE UNIQUE INDEX ux_dim_cve_current ON dim_cve (cve_id) WHERE is_current;
CREATE UNIQUE INDEX ux_dim_cve_version ON dim_cve (cve_id, effective_start_date);
COMMENT ON TABLE dim_cve IS 'CVE dimension, SCD Type 2: a new version is created when NVD modifies the CVE.';

CREATE TABLE dim_product (
    product_key             BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vendor_name             VARCHAR(255) NOT NULL,           -- normalised CPE vendor, e.g. 'apache'
    product_name            VARCHAR(255) NOT NULL,           -- normalised CPE product, e.g. 'http_server'
    vendor_product_name     VARCHAR(511) NOT NULL UNIQUE,    -- 'apache:http_server'
    source_vendor_name      VARCHAR(255),                    -- display form, e.g. 'Apache'
    source_product_name     VARCHAR(255),                    -- display form, e.g. 'Http Server'
    cpe_part                CHAR(1),                         -- a / o / h
    normalization_status    VARCHAR(30)  NOT NULL,           -- 'CPE', 'Unknown'
    UNIQUE (vendor_name, product_name)
);
COMMENT ON TABLE dim_product IS 'Affected vendor/product as named by NVD CPE strings.';

CREATE TABLE dim_software (
    software_key                BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    software_name               VARCHAR(255) NOT NULL,       -- as recorded in the inventory
    software_vendor             VARCHAR(255),
    software_version            VARCHAR(100) NOT NULL,       -- BR-04: kept as text
    normalized_software_name    VARCHAR(255) NOT NULL,
    normalized_vendor_name      VARCHAR(255),
    normalization_status        VARCHAR(30)  NOT NULL,       -- 'Mapped', 'Unmapped', 'Unknown'
    UNIQUE (normalized_software_name, software_version)
);
COMMENT ON TABLE dim_software IS 'Installed software product + version found in the asset inventory.';

CREATE TABLE dim_asset (
    asset_key               BIGINT       GENERATED BY DEFAULT AS IDENTITY (START WITH 1001) PRIMARY KEY,
    asset_id                VARCHAR(100) NOT NULL,           -- natural key, e.g. AST-APACHE-01
    hostname                VARCHAR(255),
    ip_address              VARCHAR(45),
    asset_type              VARCHAR(50),
    os_name                 VARCHAR(100),
    os_version              VARCHAR(50),
    environment             VARCHAR(30),
    criticality_level       VARCHAR(20),
    asset_criticality_score SMALLINT,
    exposure_level          VARCHAR(30),
    internet_exposed_flag   BOOLEAN,
    active_flag             BOOLEAN,
    asset_status            VARCHAR(30),                     -- Active / Maintenance / Decommissioned
    asset_owner             VARCHAR(255),
    department_name         VARCHAR(100),
    location_name           VARCHAR(100),
    row_hash                CHAR(32)     NOT NULL,
    effective_start_date    DATE         NOT NULL,
    effective_end_date      DATE         NOT NULL DEFAULT DATE '9999-12-31',
    is_current              BOOLEAN      NOT NULL DEFAULT TRUE,
    CHECK (effective_end_date >= effective_start_date)
);
CREATE UNIQUE INDEX ux_dim_asset_current ON dim_asset (asset_id) WHERE is_current;
CREATE UNIQUE INDEX ux_dim_asset_version ON dim_asset (asset_id, effective_start_date);
COMMENT ON TABLE dim_asset IS 'Asset dimension, SCD Type 2 on owner/department/criticality/exposure/environment/location changes.';

CREATE TABLE dim_cvss (
    cvss_key                BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cvss_version            VARCHAR(5),                      -- 2.0 / 3.0 / 3.1 / 4.0
    base_score              NUMERIC(3,1) CHECK (base_score BETWEEN 0 AND 10),
    base_severity           VARCHAR(20),                     -- NONE / LOW / MEDIUM / HIGH / CRITICAL
    attack_vector           VARCHAR(30),
    attack_complexity       VARCHAR(30),
    privileges_required     VARCHAR(30),
    user_interaction        VARCHAR(30),
    scope                   VARCHAR(30),
    confidentiality_impact  VARCHAR(30),
    integrity_impact        VARCHAR(30),
    availability_impact     VARCHAR(30),
    vector_string           VARCHAR(255)
);
CREATE UNIQUE INDEX ux_dim_cvss_natural ON dim_cvss (cvss_version, vector_string, base_score) NULLS NOT DISTINCT;
COMMENT ON TABLE dim_cvss IS 'One row per distinct CVSS version + vector + score combination.';

CREATE TABLE dim_cwe (
    cwe_key         BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cwe_code        VARCHAR(30)  NOT NULL UNIQUE,            -- e.g. CWE-79, NVD-CWE-noinfo
    cwe_description VARCHAR(255)
);

CREATE TABLE dim_kev_status (
    kev_status_key              BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    is_kev_listed               BOOLEAN      NOT NULL,
    known_ransomware_use        VARCHAR(20),                 -- Known / Unknown / Not Applicable
    forensic_triage_required    BOOLEAN,
    required_action             TEXT
);
CREATE UNIQUE INDEX ux_dim_kev_status_natural ON dim_kev_status
    (is_kev_listed, known_ransomware_use, forensic_triage_required, md5(coalesce(required_action, '')))
    NULLS NOT DISTINCT;
COMMENT ON TABLE dim_kev_status IS 'Junk dimension of KEV flags + required action. Includes a "Not KEV listed" member.';

CREATE TABLE dim_risk_band (
    risk_band_key   BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    risk_band_name  VARCHAR(20)  NOT NULL UNIQUE,            -- Critical / High / Medium / Low
    minimum_score   NUMERIC(6,2) NOT NULL,                   -- inclusive
    maximum_score   NUMERIC(6,2) NOT NULL,                   -- inclusive
    priority_rank   SMALLINT     NOT NULL UNIQUE,            -- 1 = act first
    remediation_sla_days INTEGER NOT NULL,                   -- target days to fix (non-KEV findings)
    CHECK (maximum_score >= minimum_score)
);
COMMENT ON TABLE dim_risk_band IS 'Static banding of the 0-100 risk priority score.';


-- 2. Bridge tables

CREATE TABLE bridge_cve_product (
    cve_product_key          BIGINT       GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    cve_key                  BIGINT       NOT NULL REFERENCES dim_cve (cve_key),
    product_key              BIGINT       NOT NULL REFERENCES dim_product (product_key),
    cpe_criteria             TEXT         NOT NULL,
    cpe_version              VARCHAR(100),                   -- exact pinned version, NULL when a range is used
    version_start_including  VARCHAR(100),
    version_start_excluding  VARCHAR(100),
    version_end_including    VARCHAR(100),
    version_end_excluding    VARCHAR(100),
    default_status           VARCHAR(20)  NOT NULL DEFAULT 'affected',
    match_source             VARCHAR(30)  NOT NULL DEFAULT 'NVD CPE'
);
CREATE UNIQUE INDEX ux_bridge_cve_product ON bridge_cve_product
    (cve_key, product_key, cpe_criteria, version_start_including, version_start_excluding, version_end_including, version_end_excluding)
    NULLS NOT DISTINCT;
CREATE INDEX ix_bridge_cve_product_product ON bridge_cve_product (product_key);
COMMENT ON TABLE bridge_cve_product IS 'Many-to-many CVE <-> affected product, with the affected version range from NVD.';

CREATE TABLE bridge_cve_cwe (
    cve_key         BIGINT       NOT NULL REFERENCES dim_cve (cve_key),
    cwe_key         BIGINT       NOT NULL REFERENCES dim_cwe (cwe_key),
    PRIMARY KEY (cve_key, cwe_key)
);
CREATE INDEX ix_bridge_cve_cwe_cwe ON bridge_cve_cwe (cwe_key);

CREATE TABLE bridge_product_software_map (
    product_software_map_key BIGINT       GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    product_key              BIGINT       NOT NULL REFERENCES dim_product (product_key),
    software_key             BIGINT       NOT NULL REFERENCES dim_software (software_key),
    match_method             VARCHAR(50)  NOT NULL,          -- Exact Name / Normalized Name / CPE / Manual Mapping
    match_confidence         VARCHAR(30)  NOT NULL,          -- Confirmed / Probable / Manual Review / Unmatched
    mapping_notes            TEXT,
    is_active                BOOLEAN      NOT NULL DEFAULT TRUE,
    UNIQUE (product_key, software_key)
);
COMMENT ON TABLE bridge_product_software_map IS 'Links installed software to the NVD product it corresponds to (BR-07).';


-- 3. Fact tables

CREATE TABLE fact_vulnerability_intelligence_snapshot (
    vulnerability_snapshot_key  BIGINT       GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    assessment_date_key         INTEGER      NOT NULL REFERENCES dim_date (date_key),   -- EPSS score date
    published_date_key          INTEGER      NOT NULL REFERENCES dim_date (date_key),
    last_modified_date_key      INTEGER      NOT NULL REFERENCES dim_date (date_key),
    kev_date_added_key          INTEGER      NOT NULL REFERENCES dim_date (date_key),
    kev_due_date_key            INTEGER      NOT NULL REFERENCES dim_date (date_key),
    cve_key                     BIGINT       NOT NULL REFERENCES dim_cve (cve_key),
    cvss_key                    BIGINT       NOT NULL REFERENCES dim_cvss (cvss_key),
    kev_status_key              BIGINT       NOT NULL REFERENCES dim_kev_status (kev_status_key),
    risk_band_key               BIGINT       NOT NULL REFERENCES dim_risk_band (risk_band_key),
    epss_score                  NUMERIC(8,6) CHECK (epss_score BETWEEN 0 AND 1),
    epss_percentile             NUMERIC(8,6) CHECK (epss_percentile BETWEEN 0 AND 1),
    cvss_base_score             NUMERIC(3,1) CHECK (cvss_base_score BETWEEN 0 AND 10),
    kev_listed_flag             SMALLINT     NOT NULL CHECK (kev_listed_flag IN (0, 1)),
    ransomware_use_flag         SMALLINT     NOT NULL CHECK (ransomware_use_flag IN (0, 1)),
    forensic_triage_flag        SMALLINT     NOT NULL CHECK (forensic_triage_flag IN (0, 1)),
    days_to_kev_due_date        INTEGER,                     -- negative = overdue; NULL when not in KEV
    vulnerability_risk_score    NUMERIC(6,2) NOT NULL CHECK (vulnerability_risk_score BETWEEN 0 AND 100),
    batch_id                    VARCHAR(40)  NOT NULL,
    loaded_at                   TIMESTAMP    NOT NULL DEFAULT clock_timestamp(),
    UNIQUE (assessment_date_key, cve_key)
);
CREATE INDEX ix_fvis_cve       ON fact_vulnerability_intelligence_snapshot (cve_key);
CREATE INDEX ix_fvis_kev       ON fact_vulnerability_intelligence_snapshot (kev_status_key);
CREATE INDEX ix_fvis_risk_band ON fact_vulnerability_intelligence_snapshot (risk_band_key);
COMMENT ON TABLE fact_vulnerability_intelligence_snapshot IS
    'Periodic snapshot. Grain: one row per CVE per EPSS snapshot date. Risk score = (CVSS/10*35 + EPSS*30 + KEV*20) rescaled from 0-85 to 0-100.';

CREATE TABLE fact_asset_software_inventory_snapshot (
    asset_inventory_snapshot_key BIGINT      GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    snapshot_date_key           INTEGER      NOT NULL REFERENCES dim_date (date_key),
    asset_key                   BIGINT       NOT NULL REFERENCES dim_asset (asset_key),
    software_key                BIGINT       NOT NULL REFERENCES dim_software (software_key),
    installed_software_count    INTEGER      NOT NULL DEFAULT 1,
    active_asset_flag           SMALLINT     NOT NULL CHECK (active_asset_flag IN (0, 1)),
    internet_exposed_flag       SMALLINT     NOT NULL CHECK (internet_exposed_flag IN (0, 1)),
    asset_criticality_score     SMALLINT     NOT NULL CHECK (asset_criticality_score BETWEEN 1 AND 4),
    batch_id                    VARCHAR(40)  NOT NULL,
    loaded_at                   TIMESTAMP    NOT NULL DEFAULT clock_timestamp(),
    UNIQUE (snapshot_date_key, asset_key, software_key)
);
CREATE INDEX ix_fasis_asset    ON fact_asset_software_inventory_snapshot (asset_key);
CREATE INDEX ix_fasis_software ON fact_asset_software_inventory_snapshot (software_key);
COMMENT ON TABLE fact_asset_software_inventory_snapshot IS
    'Periodic snapshot. Grain: one row per asset, installed software/version and snapshot date.';

CREATE TABLE fact_asset_vulnerability_exposure (
    asset_vulnerability_exposure_key BIGINT  GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    assessment_date_key         INTEGER      NOT NULL REFERENCES dim_date (date_key),
    remediation_due_date_key    INTEGER      NOT NULL REFERENCES dim_date (date_key),
    first_detected_date_key     INTEGER      NOT NULL REFERENCES dim_date (date_key),
    cve_key                     BIGINT       NOT NULL REFERENCES dim_cve (cve_key),
    asset_key                   BIGINT       NOT NULL REFERENCES dim_asset (asset_key),
    software_key                BIGINT       NOT NULL REFERENCES dim_software (software_key),
    product_key                 BIGINT       NOT NULL REFERENCES dim_product (product_key),
    cvss_key                    BIGINT       NOT NULL REFERENCES dim_cvss (cvss_key),
    kev_status_key              BIGINT       NOT NULL REFERENCES dim_kev_status (kev_status_key),
    risk_band_key               BIGINT       NOT NULL REFERENCES dim_risk_band (risk_band_key),
    match_confidence            VARCHAR(30)  NOT NULL CHECK (match_confidence IN ('Confirmed', 'Probable', 'Manual Review', 'Unmatched')),
    version_match_flag          SMALLINT     NOT NULL CHECK (version_match_flag IN (0, 1)),
    asset_criticality_score     SMALLINT     NOT NULL CHECK (asset_criticality_score BETWEEN 1 AND 4),
    internet_exposed_flag       SMALLINT     NOT NULL CHECK (internet_exposed_flag IN (0, 1)),
    epss_score                  NUMERIC(8,6) CHECK (epss_score BETWEEN 0 AND 1),
    cvss_base_score             NUMERIC(3,1) CHECK (cvss_base_score BETWEEN 0 AND 10),
    kev_listed_flag             SMALLINT     NOT NULL CHECK (kev_listed_flag IN (0, 1)),
    risk_priority_score         NUMERIC(6,2) NOT NULL CHECK (risk_priority_score BETWEEN 0 AND 100),
    remediation_status          VARCHAR(30)  NOT NULL CHECK (remediation_status IN ('Open', 'In Progress', 'Mitigated', 'Closed')),
    days_open                   INTEGER      NOT NULL CHECK (days_open >= 0),
    batch_id                    VARCHAR(40)  NOT NULL,
    loaded_at                   TIMESTAMP    NOT NULL DEFAULT clock_timestamp(),
    UNIQUE (assessment_date_key, cve_key, asset_key, software_key)
);
CREATE INDEX ix_fave_cve       ON fact_asset_vulnerability_exposure (cve_key);
CREATE INDEX ix_fave_asset     ON fact_asset_vulnerability_exposure (asset_key);
CREATE INDEX ix_fave_software  ON fact_asset_vulnerability_exposure (software_key);
CREATE INDEX ix_fave_risk_band ON fact_asset_vulnerability_exposure (risk_band_key);
COMMENT ON TABLE fact_asset_vulnerability_exposure IS
    'Exposure fact. Grain: one row per CVE, affected asset, installed software/version and assessment date. '
    'Risk = CVSS/10*35 + EPSS*30 + KEV*20 + criticality/4*10 + internet_exposed*5 (0-100).';
